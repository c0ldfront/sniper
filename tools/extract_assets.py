#!/usr/bin/env python3
"""Generate the Sniper 87 asset files from your own copy of the original game.

No original asset bytes are stored in this repository. This script reads the
original sniper87.zip (or SNIPER.EXE alone), checks that it is the version the
reconstruction targets, and writes into --out (default build/assets):

  sniper_assets.c   every resource payload of SNIPER.EXE as C arrays, indexed
                    by type/id/language (declared in include/sniper_assets.h)
  sniper_assets.rc  the same payloads as Win32 resource-compiler input
  files/            game data files read at runtime (from the zip only)

Uses only the Python standard library. Outputs are deterministic; unchanged
files are not rewritten, and every write is atomic.
"""
import argparse
import hashlib
import io
import os
import struct
import sys
import zipfile
from pathlib import Path

EXE_SHA256 = "8aadc97250639528bde00149ad67365e603e991ee606196e59b0b89d156033d0"
ZIP_FILES = {  # name in sniper87.zip -> SHA-256
    "SNIPER.EXE": EXE_SHA256,
    "LOCAL.LVL": "34fac6884535ed32114e361a7187a27f4f283f736315a31c4a9e76e09fdac577",
    "SNIPER.HLP": "a87035714c90d167ed029a27613868a0b6d0315074a802b4de1f111c40179266",
    "ARENA.LST": "a543dc70e95ce2237e31e01a2d8c41bab42a6006470905cfc41392ff0526c3ed",
    "45538382.LVL": "6b97dc5afc299baf3b36fe43cd1021d8b23eaa45a090cc132405d30ac7be98a4",
    "LICENSE.TXT": "501be3dbd36b05fac94fbfb4fc16a73eeb0115e7cedca161d1b36168c426c083",
}
RT_NAMES = {1: "RT_CURSOR", 2: "RT_BITMAP", 3: "RT_ICON", 4: "RT_MENU", 5: "RT_DIALOG", 6: "RT_STRING",
            9: "RT_ACCELERATOR", 10: "RT_RCDATA", 12: "RT_GROUP_CURSOR", 14: "RT_GROUP_ICON", 16: "RT_VERSION"}


class Bad(Exception):
    pass


def resources(exe):
    """Return [(type, id, language, data_rva, payload)] for every leaf of the PE resource tree.

    type and id are ints for numeric entries and str for named ones. The list is in
    payload order (data RVA), which is the order the resource compiler reproduces.
    """
    if exe[:2] != b"MZ":
        raise Bad("not a PE executable (no MZ header)")
    pe = struct.unpack_from("<I", exe, 0x3C)[0]
    if exe[pe:pe + 4] != b"PE\0\0":
        raise Bad("not a PE executable (no PE signature)")
    sections_count, opt_size = struct.unpack_from("<H", exe, pe + 6)[0], struct.unpack_from("<H", exe, pe + 20)[0]
    opt = pe + 24
    if struct.unpack_from("<H", exe, opt)[0] != 0x10B:
        raise Bad("expected a 32-bit (PE32) executable")
    rsrc_rva, rsrc_size = struct.unpack_from("<II", exe, opt + 96 + 2 * 8)
    sections = []
    for i in range(sections_count):
        s = opt + opt_size + 40 * i
        vsize, va, raw_size, raw_ptr = struct.unpack_from("<IIII", exe, s + 8)
        sections.append((va, max(vsize, raw_size), raw_ptr))

    def offset(rva):
        for va, size, raw in sections:
            if va <= rva < va + size:
                return raw + rva - va
        raise Bad(f"RVA 0x{rva:x} is outside every section")

    base = offset(rsrc_rva)

    def name(field):
        if field & 0x80000000:
            at = base + (field & 0x7FFFFFFF)
            length = struct.unpack_from("<H", exe, at)[0]
            return exe[at + 2:at + 2 + 2 * length].decode("utf-16-le")
        return field

    def entries(at):
        named, ids = struct.unpack_from("<HH", exe, base + at + 12)
        for i in range(named + ids):
            field, target = struct.unpack_from("<II", exe, base + at + 16 + 8 * i)
            yield name(field), target

    out = []
    for rtype, t in entries(0):
        for rid, n in entries(t & 0x7FFFFFFF):
            for lang, leaf in entries(n & 0x7FFFFFFF):
                if leaf & 0x80000000:
                    raise Bad("unexpected fourth resource-directory level")
                rva, size = struct.unpack_from("<II", exe, base + leaf)
                out.append((rtype, rid, lang, rva, exe[offset(rva):offset(rva) + size]))
    if not out or rsrc_size == 0:
        raise Bad("the executable has no resources")
    return sorted(out, key=lambda r: r[3])


def c_ident(value):
    return str(value) if isinstance(value, int) else "".join(ch if ch.isalnum() else "_" for ch in value)


def render_c(res):
    lines = ["/* Generated by tools/extract_assets.py from SNIPER.EXE (SHA-256",
             f" * {EXE_SHA256}). Do not edit or commit. */",
             '#include "sniper_assets.h"', ""]
    table = []
    for rtype, rid, lang, _, data in res:
        sym = f"asset_{c_ident(rtype)}_{c_ident(rid)}_{lang}"
        lines.append(f"static const unsigned char {sym}[{max(len(data), 1)}]={{")
        for i in range(0, len(data), 20):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 20]) + ",")
        lines.append("};")
        type_id = rtype if isinstance(rtype, int) else 0
        type_name = "NULL" if isinstance(rtype, int) else f'"{rtype}"'
        res_id = rid if isinstance(rid, int) else 0
        res_name = "NULL" if isinstance(rid, int) else f'"{rid}"'
        table.append(f"    {{{type_id},{type_name},{res_id},{res_name},{lang},{len(data)}u,{sym}}},")
    lines += ["", "const SniperAsset sniper_assets[]={", *table, "};",
              "const size_t sniper_asset_count=sizeof sniper_assets/sizeof sniper_assets[0];", "",
              "const SniperAsset *sniper_asset_find(unsigned type_id,const char *type_name,unsigned id){",
              "    for(size_t i=0;i<sniper_asset_count;i++){",
              "        const SniperAsset *a=&sniper_assets[i];",
              "        int same_type=type_name?(a->type_name&&strcmp(a->type_name,type_name)==0):(!a->type_name&&a->type_id==type_id);",
              "        if(same_type&&!a->name&&a->id==id)return a;",
              "    }",
              "    return NULL;",
              "}", ""]
    return "\n".join(lines)


def render_rc(res):
    lines = ["/* Generated by tools/extract_assets.py from SNIPER.EXE. Original raw resource",
             " * payloads with their original type, ID and language. Do not edit or commit. */"]
    language = None
    for rtype, rid, lang, _, data in res:
        if lang != language:
            lines.append(f"LANGUAGE {lang & 0x3FF}, {lang >> 10}")
            language = lang
        lines.append(f"{rid} {rtype}")
        lines.append("BEGIN")
        words = [f"0x{data[i] | data[i + 1] << 8:04x}" for i in range(0, len(data) - 1, 2)]
        if len(data) % 2:
            words.append(f'"\\x{data[-1]:02x}"')
        for i in range(0, len(words), 12):
            lines.append("    " + ", ".join(words[i:i + 12]) + ("," if i + 12 < len(words) else ""))
        lines.append("END")
    return "\n".join(lines) + "\n"


def write(path, data):
    """Atomic, idempotent write; returns True when the file changed."""
    if path.exists() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)
    return True


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--zip", type=Path, help="original sniper87.zip (resources and data files)")
    src.add_argument("--exe", type=Path, help="original SNIPER.EXE (resources only; no data files)")
    p.add_argument("--out", type=Path, default=Path("build/assets"), help="output directory (default: build/assets)")
    p.add_argument("--check", action="store_true", help="verify the input and list what would be written")
    args = p.parse_args(argv)
    try:
        files = {}
        if args.zip:
            with zipfile.ZipFile(args.zip) as z:
                names = {n.upper(): n for n in z.namelist()}
                for wanted, digest in ZIP_FILES.items():
                    if wanted not in names:
                        raise Bad(f"{args.zip} has no {wanted}; is this the Sniper 87 archive?")
                    data = z.read(names[wanted])
                    if hashlib.sha256(data).hexdigest() != digest:
                        raise Bad(f"{wanted} in {args.zip} is not the expected Sniper 87 file (SHA-256 mismatch)")
                    files[wanted] = data
            exe = files["SNIPER.EXE"]
        else:
            exe = args.exe.read_bytes()
            if hashlib.sha256(exe).hexdigest() != EXE_SHA256:
                raise Bad(f"{args.exe} is not the Sniper 87 SNIPER.EXE this reconstruction targets (SHA-256 mismatch)")
        res = resources(exe)
    except (OSError, zipfile.BadZipFile, struct.error, Bad) as exc:
        print(f"extract_assets: error: {exc}", file=sys.stderr)
        return 1
    outputs = {args.out / "sniper_assets.c": render_c(res).encode(), args.out / "sniper_assets.rc": render_rc(res).encode()}
    outputs.update({args.out / "files" / n: d for n, d in files.items()})
    total = sum(len(r[4]) for r in res)
    print(f"{len(res)} resources ({total} bytes) from SNIPER.EXE; {len(files)} data files")
    for path, data in outputs.items():
        if args.check:
            print(f"would write {path}")
        elif write(path, data):
            print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
