def checksum(data: bytes) -> int:
    return sum(x[0] for x in struct.iter_unpack('<I', data[:len(data)//4*4])) & 0xffffffff


def fixed_text(data: bytes) -> bytes:
    return data.split(b'\0', 1)[0]


def signed_byte(value: int) -> int:
    return (value + 128) % 256 - 128


def pickup_pool(value):
    if value == 'none':
        return ()
    try:
        kinds=tuple(int(part) for part in value.split(','))
        if not kinds or any(not 1 <= abs(k) <= 21 for k in kinds):
            raise ValueError
        return kinds
    except ValueError:
        raise argparse.ArgumentTypeError('use comma-separated prize IDs ±1..21, or none')


class Accounts:
    def __init__(self, path):
        self.db = sqlite3.connect(path, check_same_thread=False)
        self.db.execute('CREATE TABLE IF NOT EXISTS accounts (name BLOB PRIMARY KEY, salt BLOB, digest BLOB, kills INTEGER DEFAULT 0, deaths INTEGER DEFAULT 0, points INTEGER DEFAULT 0, squad BLOB DEFAULT X\'\')')
        self.db.execute('CREATE TABLE IF NOT EXISTS squads (name BLOB PRIMARY KEY, salt BLOB, digest BLOB)')
        self.db.commit()

    @staticmethod
    def digest(password, salt):
        return hashlib.scrypt(password, salt=salt, n=16384, r=8, p=1)

    def login(self, name, password, create):
        if not name or len(name) > 31 or any(c < 32 or c == 127 for c in name):
            return 3
        row = self.db.execute('SELECT salt,digest FROM accounts WHERE name=?', (name,)).fetchone()
        if row is None:
            if not create:
                return 1
            salt = secrets.token_bytes(16)
            self.db.execute('INSERT INTO accounts(name,salt,digest) VALUES (?,?,?)', (name, salt, self.digest(password,salt)))
            self.db.commit()
            return 0
        return 0 if hmac.compare_digest(row[1], self.digest(password,row[0])) else 2

    def reset_score(self, name):
        # Scores belong to an authenticated connection, not account lifetime.
        self.db.execute('UPDATE accounts SET kills=0,deaths=0,points=0 WHERE name=?',(name,))
        self.db.commit()

    def profile(self, name):
        return self.db.execute('SELECT kills,deaths,points,squad FROM accounts WHERE name=?', (name,)).fetchone()


    def squad(self, account, name, password):
        if not name or len(name)>31 or any(c<32 or c==127 for c in name):
            return 2
        row=self.db.execute('SELECT salt,digest FROM squads WHERE name=?',(name,)).fetchone()
        status=1
        if row is None:
            salt=secrets.token_bytes(16)
            self.db.execute('INSERT INTO squads VALUES(?,?,?)',(name,salt,self.digest(password,salt)))
            status=0
        elif not hmac.compare_digest(row[1],self.digest(password,row[0])):
            return 2
        self.db.execute('UPDATE accounts SET squad=? WHERE name=?',(name,account))
        self.db.commit()
        return status

    def death(self, killer, victim, points):
        self.db.execute('UPDATE accounts SET deaths=MIN(32767,deaths+1) WHERE name=?',(victim,))
        if killer is not None:
            # The original score-list UI renders points as signed int32.
            self.db.execute('UPDATE accounts SET points=MIN(2147483647,MAX(0,points+?)), kills=MIN(32767,kills+?) WHERE name=?',
                            (points,int(killer!=victim),killer))
        self.db.commit()


class ActivitySocket:
    """Track actual inbound datagrams, including pings with no app payload."""
    def __init__(self,sock):
        self.socket=sock
        self.last_activity=time.monotonic()
    def __getattr__(self,name):
        return getattr(self.socket,name)
    def recv(self,size):
        data=self.socket.recv(size)
        self.last_activity=time.monotonic()
        return data


@dataclass(eq=False)
class Client:
    session: object
    outbox: queue.Queue = field(default_factory=lambda: queue.Queue(maxsize=1024))
    name: bytes | None = None
    player: int | None = None
    ship: int = 0
    team: int = 0
    option: int = 0
    attached: int = -1
    spectating: int = -1
    last_state: dict | None = None
    voice: dict = field(default_factory=dict)
    death_at: float = -1000
    state_count: int = 0
    alive: bool = True

    def send(self, opcode, *, reliable=True, **fields):
        packet=encode('s2c',opcode,**fields)
        try:
            self.outbox.put_nowait((packet,reliable))
        except queue.Full:
            # A slow destination must not disconnect the broadcasting sender.
            self.alive=False


class Arena:
    def __init__(self, data, port, idle_timeout=120, map_path=None, team_sharing=False,
                 prizes=None):
        self.lock = threading.RLock()
        self.clients = []
        self.accounts = Accounts(data / 'accounts.sqlite3')
        self.port = port
        self.idle_timeout = idle_timeout
        self.push_assets = []
        if map_path == 'open-arena':
            self.map = open_arena()
        else:
            self.map = Path(map_path).read_bytes() if map_path else game_file('LOCAL.LVL')
        self.exe = game_file('SNIPER.EXE')
        self.arena_list = f'Local Arena,127.0.0.1,{port}\r\n'.encode()
        self.news = b'Independent local SNIPER v87 server.\r\n'
        self.pickups = {}
        # All21 original positive rewards, not just the six starter upgrades.
        # Distribution is an explicit local arena policy.
        self.prizes = tuple(range(1,22)) if prizes is None else tuple(prizes)
        if any(not 1 <= abs(k) <= 21 for k in self.prizes):
            raise ValueError('unsupported prize ID')
        self.next_pickup = time.monotonic()+3
        self.rng = random.Random()
        self.tiles = {(v & 0xfff,(v>>12)&0xfff):(v>>24) for (v,) in struct.iter_unpack('<I',self.map)}
        self.events = open(data/'events.jsonl','a',buffering=1)
        self.settings = offline_settings()
        if team_sharing:
            # Original404910 shares pickups;404530 also resets ship on
            # team change under this same recovered setting.
            configured=bytearray(self.settings)
            struct.pack_into('<I',configured,0xe4,1)
            self.settings=bytes(configured)

    def event(self, event, **values):
        self.events.write(json.dumps(dict(time=time.time(),event=event,**values))+'\n')

    def peers(self):
        return [c for c in self.clients if c.alive and c.player is not None]

    def broadcast(self, opcode, *, exclude=None, **fields):
        for peer in self.peers():
            if peer is not exclude:
                peer.send(opcode, **fields)

    def announce(self, destination, source):
        kills,deaths,points,squad = self.accounts.profile(source.name)
        destination.send(3,player=source.player,ship_type=source.ship,name=source.name,
                         squad=squad,field43=source.team & 0xffffffff,field47=kills,
                         field49=deaths,field4b=points,field4f=source.attached,field51=source.option)

    def leave(self,c):
        if c.player is not None:
            player = c.player
            c.player = None
            c.last_state = None
            c.voice.clear()
            c.attached = -1
            c.spectating = -1
            c.death_at = -1000
            c.state_count = 0
            for peer in self.peers():
                if peer.attached == player:
                    peer.attached = -1
                    self.broadcast(16,player=peer.player,target=-1)
            self.broadcast(4,player=player)
            self.event('leave',player=player)

    def download(self,c,data):
        c.send(13,total_size=len(data))
        for offset in range(0,len(data),4096):
            c.send(12,offset=offset,data=data[offset:offset+4096])
        c.send(12,offset=0xffffffff,data=b'')
        self.event('download_queued',bytes=len(data))

    def handle(self,c,payload):
        msg = decode('c2s',payload)
        op,f = msg['opcode'],msg['fields']
        if op != 3:
            self.event('receive',opcode=op,bytes=len(payload),player=c.player)
        if op == 9:
            self.leave(c)
            c.name=None
            name,password = fixed_text(f['name']),fixed_text(f['password'])
            status = self.accounts.login(name,password,bool(f['create_user']))
            if status == 0 and any(p is not c and p.alive and p.name==name for p in self.clients):
                status = 3
            if status == 0:
                self.accounts.reset_score(name)
                c.name=name
            c.send(10,status=status,minimum_version=87,
                   map_checksum=sum(self.map[:len(self.map)//4*4]) & 0xffffffff,
                   field0a=checksum(self.exe),arena_list_checksum=checksum(self.arena_list))
            self.event('login_reply',status=status)
            return
        if c.name is None:
            raise ValueError('application request before authentication')
        if op in (11,12,13,18):
            self.download(c,{11:self.exe,12:self.map,13:self.news,18:self.arena_list}[op])
        elif op == 14:
            # Remove file data not yet handed to transport. Already sent reliable
            # frames cannot be retracted without corrupting sequence ordering.
            retained=[]
            while not c.outbox.empty():
                item=c.outbox.get_nowait()
                if item[0][0] not in (12,13): retained.append(item)
            for item in retained: c.outbox.put_nowait(item)
            self.event('download_done_or_cancel')
        elif op == 19:
            status=self.accounts.squad(c.name,fixed_text(f['name']),fixed_text(f['password']))
            c.send(19,status=status)
            self.event('squad_reply',status=status)
        elif op == 10:
            rows=self.accounts.db.execute('SELECT name,squad,kills,deaths,points FROM accounts ORDER BY name').fetchall()
            c.send(11,records=[dict(string1=name,string2=squad,value1=kills,value2=deaths,value3=points)
                               for name,squad,kills,deaths,points in rows])
        elif op == 1:
            if self.settings is None:
                raise ValueError('settings unavailable')
            if f['ship_type'] not in range(5):
                raise ValueError('invalid ship selection')
            self.leave(c)
            used={p.player for p in self.peers()}
            c.player=next((n for n in range(1,128) if n not in used),None)
            if c.player is None:
                raise ValueError('arena full')
            c.ship=f['ship_type']; c.team=f['team']; c.option=f['option']
            if c.ship not in range(5):
                raise ValueError('invalid ship selection')
            c.send(1,player=c.player)
            c.send(17,opaque=self.settings)
            for peer in self.peers():
                self.announce(c,peer)
                if peer is not c:
                    self.announce(peer,c)
            c.send(2)
            for asset in self.push_assets: self.push_asset(c,asset)
            for peer in self.peers():
                if peer is not c and peer.last_state:
                    state=peer.last_state.copy()
                    state['flags']=0 # old weapons must not fire again on join
                    state['state_byte']=signed_byte(state['state_byte'])
                    state['extra_byte']=signed_byte(state['extra_byte'])
                    c.send(5,player=peer.player,**state)
            for (x,y),(kind,expires) in self.pickups.items():
                lifetime=max(0,int((expires-time.monotonic())*100))
                if lifetime: c.send(9,event=kind,word2=x,word4=y,value=lifetime)
            self.event('ready',player=c.player,ship=c.ship,team=c.team,voice=c.option)
        elif op == 2:
            self.leave(c)
        elif c.player is None:
            raise ValueError('game request before arena join')
        elif op == 3:
            c.state_count+=1
            if c.state_count == 1 or f['flags'] & 7:
                self.event('state',player=c.player,x=f['word2'],y=f['word4'],weapon=f['flags']&7)
            c.last_state=f.copy()
            out=f.copy();out['player']=c.player
            out['state_byte']=signed_byte(out['state_byte'])
            out['extra_byte']=signed_byte(out['extra_byte'])
            self.broadcast(5,exclude=c,reliable=False,**out)
        elif op == 6:
            target=f['target']
            for peer in self.peers():
                if peer is not c and (target == -1 or (target == -2 and peer.team == c.team) or peer.player == target):
                    peer.send(7,sender=c.player,target=target,text=f['text'])
        elif op == 8:
            if not any(p.player==f['action'] for p in self.peers()):
                return
            c.spectating=f['action']
        elif op == 16:
            c.team=f['team']
            self.broadcast(15,player=c.player,team=c.team)
            for peer in self.peers():
                if peer.attached==c.player:
                    peer.attached=-1
                    self.broadcast(16,player=peer.player,target=-1)
        elif op == 17:
            target=f['target']
            if target != -1 and not any(p.player==target and p is not c for p in self.peers()):
                return
            if target != -1:
                parent=next(p for p in self.peers() if p.player==target)
                if parent.team != c.team or parent.ship == 4: return
                seen={c.player}
                while parent is not None:
                    if parent.player in seen: return
                    seen.add(parent.player)
                    parent=next((p for p in self.peers() if p.player==parent.attached),None)
            c.attached=target
            self.broadcast(16,player=c.player,target=target)
        elif op == 15:
            if not 0 <= f['slot'] < 16 or len(f['payload'])>1024*1024:
                raise ValueError('invalid voice slot or size')
            if f['payload']: c.voice[f['slot']]=f['payload']
            audio=c.voice.get(f['slot'])
            if audio is None: raise ValueError('unknown voice cache reference')
            for peer in self.peers():
                if peer is not c and peer.player==f['target'] and peer.option:
                    peer.send(14,player=c.player,payload=audio)
                    self.event('voice_relay',sender=c.player,receiver=peer.player,slot=f['slot'],upload_bytes=len(f['payload']),expanded_bytes=len(audio))
        elif op == 5:
            # Client simulates damage/respawn. Local policy accepts one report
            # per death interval and grants the reported nonnegative bounty.
            now=time.monotonic()
            if now-c.death_at < 1.0: return
            killer=next((p for p in self.peers() if p.player==f['other_player']),None)
            if killer is None: return
            c.death_at=now
            points=max(0,f['value'])
            self.accounts.death(killer.name,c.name,points)
            self.broadcast(6,player=killer.player,other_player=c.player,value=points,extra=-1)
            self.event('death',killer=killer.player,victim=c.player,points=points)
        elif op == 7:
            location=(f['x'],f['y'])
            pickup=self.pickups.get(location)
            if pickup is None or pickup[1] <= time.monotonic() or pickup[0]!=f['value']:
                return
            del self.pickups[location]
            self.event('pickup_collected',player=c.player,x=f['x'],y=f['y'],kind=f['value'])
            self.broadcast(8,exclude=c,x=f['x'],y=f['y'],value=f['value'],player=c.player)
        else:
            self.event('unimplemented',opcode=op)

    def push_asset(self,c,name):
        # Original client writes supplied filenames directly. Limit this
        # server's administrative push to these reviewed generated assets.
        assets={'news.txt':self.news,'arena.lst':self.arena_list}
        if name not in assets: raise ValueError('asset is not allowlisted')
        c.send(18,filename=name.encode('ascii'),data=assets[name])
        self.event('asset_push',player=c.player,asset=name,bytes=len(assets[name]))

    def spawn_pickup(self,x,y,kind,lifetime=1500):
        if not (0<=x<1024 and 0<=y<1024 and 1<=abs(kind)<=21 and 0<lifetime<=60000):
            raise ValueError('invalid pickup')
        now=time.monotonic()
        self.pickups={pos:item for pos,item in self.pickups.items() if item[1]>now}
        if len(self.pickups)>=16 or self.tiles.get((x,y),0) or (x,y) in self.pickups:
            return False
        self.pickups[x,y]=(kind,now+lifetime/100)
        self.broadcast(9,event=kind,word2=x,word4=y,value=lifetime)
        return True

    def tick(self):
        if not self.prizes: return
        now=time.monotonic()
        if now < self.next_pickup: return
        self.next_pickup=now+3
        active=[c for c in self.peers() if c.ship<4 and c.last_state]
        if not active: return
        # Explicit local arena policy: periodically place a positive upgrade
        # near a player. The client owns pickup animation and expiry.
        c=self.rng.choice(active)
        for _ in range(20):
            x=c.last_state['word2']//16+self.rng.randint(-12,12)
            y=c.last_state['word4']//16+self.rng.randint(-12,12)
            if 0<=x<1024 and 0<=y<1024 and self.spawn_pickup(x,y,self.rng.choice(self.prizes)):
                self.event('pickup_spawn',x=x,y=y)
                break

    def serve_client(self,c):
        c.session.socket=ActivitySocket(c.session.socket)
        try:
            with c.session:
                while c.alive and not c.session.channel.closed:
                    if time.monotonic()-c.session.socket.last_activity > self.idle_timeout:
                        with self.lock: self.event('idle_timeout',player=c.player)
                        break
                    with self.lock:
                        self.tick()
                    for payload in c.session.receive(timeout=0.02):
                        with self.lock:
                            self.handle(c,payload)
                    # Fanout can enqueue many states per incoming datagram.
                    # Drain a bounded batch rather than limiting each peer to
                    # one outgoing packet per receive cycle. Preserve reliable
                    # ordering/backpressure and yield to inbound ACKs each batch.
                    for _ in range(64):
                        if c.session.channel.pending_count:
                            break
                        try:
                            payload,reliable=c.outbox.get_nowait()
                        except queue.Empty:
                            break
                        c.session.send(payload,reliable=reliable)
        except (OSError,ValueError,queue.Full,OverflowError,BufferError) as exc:
            with self.lock:
                self.event('session_error',kind=type(exc).__name__,detail=str(exc))
        finally:
            with self.lock:
                self.leave(c)
                c.alive=False
                self.clients.remove(c)


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--port',type=int,default=38383)
    ap.add_argument('--data',type=Path,default=ROOT/'data')
    ap.add_argument('--map',default=None,
                    help='v87 packed-tile level file, or "open-arena" (default: the game\'s LOCAL.LVL)')
    ap.add_argument('--team-sharing',action='store_true',
                    help='enable native team pickup sharing and ship reset on team change')
    ap.add_argument('--pickup-pool',type=pickup_pool,default=None,
                    help='comma-separated original prize IDs ±1..21, or none; default all positive IDs')
    ap.add_argument('--seed-test-accounts',action='store_true')
    ap.add_argument('--idle-timeout',type=float,default=120)
    ap.add_argument('--push-asset',action='append',choices=['news.txt','arena.lst'],default=[])
    args=ap.parse_args()
    args.data.mkdir(parents=True,exist_ok=True)
    arena=Arena(args.data,args.port,args.idle_timeout,map_path=args.map,
                team_sharing=args.team_sharing,prizes=args.pickup_pool)
    arena.push_assets=args.push_asset
    if args.seed_test_accounts:
        for name in (b'pilot_one',b'pilot_two'):
            arena.accounts.login(name,b'local_test',True)
    stopped=threading.Event()
    def stop(signum,frame): stopped.set()
    signal.signal(signal.SIGTERM,stop)
    signal.signal(signal.SIGINT,stop)
    workers=[]
    try:
        with socket.socket() as listener:
            listener.setsockopt(socket.SOL_SOCKET,socket.SO_REUSEADDR,1)
            listener.bind(('127.0.0.1',args.port));listener.listen(16)
            listener.settimeout(0.5)
            print(f'Local v87 server listening on 127.0.0.1:{args.port}',flush=True)
            while not stopped.is_set():
                try:
                    session=bootstrap_server(listener)
                    if not ipaddress.ip_address(session.socket.getpeername()[0]).is_loopback:
                        session.close()
                        raise ValueError('only loopback UDP endpoints are supported')
                    with arena.lock:
                        if len(arena.clients)>=32:
                            session.close()
                            arena.event('capacity_rejected')
                            continue
                        c=Client(session)
                        arena.clients.append(c)
                        arena.event('bootstrap')
                    workers=[w for w in workers if w.is_alive()]
                    worker=threading.Thread(target=arena.serve_client,args=(c,))
                    workers.append(worker)
                    worker.start()
                except socket.timeout:
                    continue
                except (OSError,ValueError) as exc:
                    arena.event('bootstrap_error',kind=type(exc).__name__)
    finally:
        with arena.lock:
            for c in arena.clients: c.alive=False
        for worker in workers: worker.join()
        arena.event('shutdown')
        arena.accounts.db.close()
        arena.events.close()


if __name__=='__main__':
    main()
