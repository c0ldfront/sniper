# The user's own game files, generated by `make assets` (tools/extract_assets.py).
GAME_FILES = ROOT.parent / 'build' / 'assets' / 'files'
LOCAL_CONFIG = ROOT.parent / 'src' / 'local_config.c'


def offline_settings():
    """The 288-byte settings body: the 72 offline configuration DWORDs of the
    original client, taken from the reconstructed src/local_config.c table."""
    import re
    text = LOCAL_CONFIG.read_text()
    table = text.split('defaults[72]={', 1)[1].split('};', 1)[0]
    values = [int(v) for v in re.findall(r'^\s*(-?\d+),?\s*/\*', table, re.M)]
    if len(values) != 72:
        raise ValueError(f'expected 72 configuration values in {LOCAL_CONFIG}, found {len(values)}')
    return struct.pack('<72i', *values)


def open_arena():
    """A new, original level: a 768x768 ring of tile 1 with an empty interior (see open-arena.json)."""
    lo, hi = 128, 895
    return b''.join(struct.pack('<I', x | y << 12 | 1 << 24)
                    for y in range(lo, hi + 1) for x in range(lo, hi + 1) if x in (lo, hi) or y in (lo, hi))


def game_file(name):
    path = GAME_FILES / name
    if not path.exists():
        sys.exit(f'{path} is missing: run "make assets SNIPER_ZIP=/path/to/sniper87.zip" in the repository root')
    return path.read_bytes()
